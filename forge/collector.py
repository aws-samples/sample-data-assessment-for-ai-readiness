def _write_roadmap_md(
    start_time: datetime,
    pillars: list[PillarScore],
    pillar_pct_map: dict[str, float],
    effective_weights: dict[str, float],
    forge_score: float,
    readiness_band,
) -> None:
    """Write forge_roadmap_<ts>.md with remediation sorted by score-lift potential.

    Score-lift for a pillar is estimated as:
        potential_gain = (100 - pillar_score) * (effective_weight / 100)

    Pillars are sorted by potential_gain descending (highest lift first).
    If forge_config/recommendations.yaml exists, includes AWS and partner
    solution guidance for each unmet criterion.
    Reports but does not abort on filesystem write failures.
    """
    import os
    ts_filename = start_time.strftime("%Y-%m-%dT%H-%M-%SZ")
    os.makedirs("forge_output/roadmaps", exist_ok=True)
    filename = f"forge_output/roadmaps/forge_roadmap_{ts_filename}.md"

    # Load recommendations and partner solutions (graceful if unavailable)
    recommendations = _load_recommendations()
    partner_catalog = _load_partner_solutions()

    # Build partner ID → name lookup
    partner_names = {}
    if partner_catalog and "solutions" in partner_catalog:
        for sol in partner_catalog["solutions"]:
            partner_names[sol["id"]] = sol.get("name", sol["id"])

    # Compute score-lift potential per pillar
    pillar_lifts = []
    for pillar in pillars:
        weight = effective_weights.get(pillar.code, 0.0)
        potential_gain = (100.0 - pillar.raw_score) * (weight / 100.0)
        unmet_criteria = [
            cr for cr in pillar.criteria
            if cr.relevance_status == RelevanceStatus.RELEVANT and cr.score < 0.5
        ]
        pillar_lifts.append({
            "code": pillar.code,
            "name": pillar.name,
            "score": pillar.raw_score,
            "weight": weight,
            "potential_gain": round(potential_gain, 2),
            "unmet_criteria": unmet_criteria,
        })

    # Sort by score-lift potential descending
    pillar_lifts.sort(key=lambda x: x["potential_gain"], reverse=True)

    # Generate markdown
    lines = [
        f"# FORGE Remediation Roadmap",
        f"",
        f"**Generated:** {start_time.isoformat()}",
        f"**Current FORGE Score:** {forge_score} ({readiness_band.value})",
        f"",
        f"## Remediation Priorities (by Score-Lift Potential)",
        f"",
        f"Pillars are ranked by their potential contribution to improving the overall FORGE Score.",
        f"",
    ]

    for item in pillar_lifts:
        if item["potential_gain"] <= 0:
            continue

        lines.append(f"### {item['code']}: {item['name']}")
        lines.append(f"")
        lines.append(f"- **Current Score:** {item['score']}%")
        lines.append(f"- **Effective Weight:** {item['weight']:.1f}%")
        lines.append(f"- **Potential Score Lift:** +{item['potential_gain']:.2f} points")
        lines.append(f"")

        if item["unmet_criteria"]:
            lines.append(f"**Unmet Criteria ({len(item['unmet_criteria'])}):**")
            lines.append(f"")
            for cr in item["unmet_criteria"]:
                criterion_key = f"{item['code']}.{cr.index}"
                lines.append(f"- [ ] {criterion_key} — {cr.name}")
                if cr.evidence and cr.evidence != "No evidence":
                    lines.append(f"  - Evidence: {cr.evidence}")

                # Include recommendations if available
                if recommendations and criterion_key in recommendations:
                    rec = recommendations[criterion_key]
                    if rec.get("action"):
                        lines.append(f"  - **Action:** {rec['action']}")
                    if rec.get("effort") or rec.get("estimated_days"):
                        effort_str = rec.get("effort", "unknown")
                        days_str = f"{rec['estimated_days']}d" if rec.get("estimated_days") else "TBD"
                        lines.append(f"  - **Effort:** {effort_str} (~{days_str})")

                    # AWS solutions
                    aws_sols = rec.get("aws_solutions", [])
                    if aws_sols:
                        lines.append(f"  - **AWS Solutions:**")
                        for sol in aws_sols:
                            lines.append(f"    - {sol['service']}: {sol['action']}")

                    # Partner solutions
                    partner_sols = rec.get("partner_solutions", [])
                    if partner_sols:
                        lines.append(f"  - **Partner Solutions:**")
                        for pid in partner_sols:
                            pname = partner_names.get(pid, pid)
                            lines.append(f"    - {pname}")

                    # Also check partner catalog for solutions that list this criterion
                    if partner_catalog and "solutions" in partner_catalog and not partner_sols:
                        applicable_partners = [
                            s for s in partner_catalog["solutions"]
                            if criterion_key in s.get("applicable_criteria", [])
                        ]
                        if applicable_partners:
                            lines.append(f"  - **Applicable Partner Products:**")
                            for ap in applicable_partners:
                                lines.append(f"    - {ap['name']} ({ap.get('category', '')})")

            lines.append(f"")
        else:
            lines.append(f"_No unmet criteria identified in this pillar._")
            lines.append(f"")

    content = "\n".join(lines)

    try:
        with open(filename, "w") as f:
            f.write(content)
    except OSError as e:
        print(f"Warning: Could not write {filename}: {e}")


def _run_config_mode(
    relevance_config: RelevanceConfig,
) -> list[CriterionResult]:
    """Execute scoring using pre-computed relevance map (config mode).

    In config mode, the Kiro Skill has already performed probe/validate/detect,
    so we just map each criterion to its pre-determined relevance status and
    score accordingly.

    Returns:
        List of criterion results.
    """
    criterion_results = []

    for criterion in CRITERIA_REGISTRY:
        criterion_key = f"{criterion.pillar}.{criterion.index}"

        # Look up pre-computed relevance status
        relevance_value = relevance_config.criteria_relevance.get(criterion_key)
        if relevance_value is None:
            # Default to RELEVANT if not in config
            relevance_status = RelevanceStatus.RELEVANT
            exclusion_reason = None
        elif isinstance(relevance_value, RelevanceStatus):
            relevance_status = relevance_value
            exclusion_reason = None if relevance_status == RelevanceStatus.RELEVANT else (
                f"Pre-computed as {relevance_status.value} by relevance config"
            )
        else:
            # String value from JSON deserialization
            try:
                relevance_status = RelevanceStatus(relevance_value)
            except ValueError:
                relevance_status = RelevanceStatus.RELEVANT
            exclusion_reason = None if relevance_status == RelevanceStatus.RELEVANT else (
                f"Pre-computed as {relevance_status.value} by relevance config"
            )

        # Determine confidence from config services
        confidence = _get_confidence_from_config(criterion, relevance_config)

        # Score criterion: placeholder 0.0 for relevant criteria
        # (deep assessment logic is not wired in the new orchestrator)
        if relevance_status == RelevanceStatus.RELEVANT:
            score = 0.0
            evidence = "Placeholder — deep assessment not wired in config mode"
        elif relevance_status == RelevanceStatus.UNDETERMINED:
            score = 0.0
            evidence = "Undetermined relevance — scored as 0"
        else:
            score = 0.0
            evidence = exclusion_reason or "Not applicable"

        criterion_results.append(CriterionResult(
            pillar=criterion.pillar,
            index=criterion.index,
            name=criterion.name,
            score=score,
            relevance_status=relevance_status,
            confidence_score=confidence,
            evidence=evidence,
            criterion_type=criterion.criterion_type,
            exclusion_reason=exclusion_reason,
            confidence_reduced=(relevance_status == RelevanceStatus.UNDETERMINED),
        ))

    return criterion_results


def _run_full_pipeline(
    region: str,
    role_arn: str = None,
    profile_name: str = None,
) -> list[CriterionResult]:
    """Execute full pipeline: probe → validate → classify → score.

    Returns:
        List of criterion results.
    """
    # Phase 1: Probe all services (using direct session, no role assumption in full pipeline)
    probe_results = run_probes(region, profile_name=profile_name)
    probe_map = {p.service_name: p for p in probe_results}

    # Phase 2: Validate provisioned services
    from forge.models import ServiceClassification
    provisioned = [
        p for p in probe_results
        if p.classification == ServiceClassification.PROVISIONED
    ]
    validation_map = {}
    with ThreadPoolExecutor(max_workers=5) as executor:
        futures = {
            executor.submit(validate_service, p.service_name, region, None, profile_name): p
            for p in provisioned
        }
        for future in futures:
            result = future.result()
            validation_map[result.service_name] = result

    # Phase 3: Run deep assessment using pillar assessors
    from forge.pillar_assessors import run_pillar_assessors
    assessor_results = run_pillar_assessors(region, profile_name)

    # Phase 4: Classify relevance and score each criterion
    criterion_results = []
    for criterion in CRITERIA_REGISTRY:
        relevance_status, reason = classify_criterion_relevance(
            criterion, probe_map, validation_map
        )

        # Determine confidence score from validation data
        confidence = _get_confidence_from_validation(criterion, validation_map)

        # Get the real score from pillar assessors
        if relevance_status == RelevanceStatus.NOT_APPLICABLE:
            score = 0.0
            evidence = reason
        elif relevance_status == RelevanceStatus.UNDETERMINED:
            score = 0.0
            evidence = reason
        else:
            # Look up the criterion in assessor results
            pillar_result = assessor_results.get(criterion.pillar, {})
            pillar_criteria_list = pillar_result.get("criteria", [])
            criterion_match = None
            for lc in pillar_criteria_list:
                if lc.get("index") == criterion.index:
                    criterion_match = lc
                    break

            if criterion_match:
                score = 1.0 if criterion_match.get("met") else 0.0
                evidence = criterion_match.get("evidence", {}).get("description", "No evidence")
            else:
                score = 0.0
                evidence = "No assessor result for this criterion"

        criterion_results.append(CriterionResult(
            pillar=criterion.pillar,
            index=criterion.index,
            name=criterion.name,
            score=score,
            relevance_status=relevance_status,
            confidence_score=confidence,
            evidence=evidence,
            criterion_type=criterion.criterion_type,
            exclusion_reason=reason if relevance_status == RelevanceStatus.NOT_APPLICABLE else None,
            confidence_reduced=(relevance_status == RelevanceStatus.UNDETERMINED),
        ))

    return criterion_results


def _build_pillar_scores(criterion_results: list[CriterionResult]) -> list[PillarScore]:
    """Aggregate criterion results into per-pillar scores.

    Computes raw_score as:
        (sum of relevant criterion scores / relevant_count) * 100

    Criteria marked not-applicable are excluded from the calculation.
    """
    # Group criteria by pillar
    pillar_criteria: dict[str, list[CriterionResult]] = {}
    for cr in criterion_results:
        pillar_criteria.setdefault(cr.pillar, []).append(cr)

    pillars = []
    for code in sorted(PILLAR_NAMES.keys()):
        criteria = pillar_criteria.get(code, [])

        relevant = [
            cr for cr in criteria
            if cr.relevance_status in (RelevanceStatus.RELEVANT, RelevanceStatus.UNDETERMINED)
        ]
        not_applicable = [
            cr for cr in criteria
            if cr.relevance_status == RelevanceStatus.NOT_APPLICABLE
        ]
        undetermined = [
            cr for cr in criteria
            if cr.relevance_status == RelevanceStatus.UNDETERMINED
        ]

        relevant_count = len(relevant)
        not_applicable_count = len(not_applicable)
        undetermined_count = len(undetermined)

        # Compute raw score: average of relevant criterion scores * 100
        if relevant_count > 0:
            score_sum = sum(cr.score for cr in relevant)
            raw_score = round((score_sum / relevant_count) * 100, 2)
        else:
            raw_score = 0.0

        pillars.append(PillarScore(
            code=code,
            name=PILLAR_NAMES.get(code, code),
            raw_score=raw_score,
            relevant_count=relevant_count,
            not_applicable_count=not_applicable_count,
            undetermined_count=undetermined_count,
            criteria=criteria,
        ))

    return pillars


def _get_confidence_from_config(
    criterion, relevance_config: RelevanceConfig
) -> float:
    """Extract confidence score for a criterion from relevance config services."""
    if not criterion.services:
        return 1.0

    confidences = []
    for service in criterion.services:
        svc_data = relevance_config.services.get(service)
        if svc_data and isinstance(svc_data, dict):
            conf = svc_data.get("confidence", 0.5)
            confidences.append(conf)

    if confidences:
        return min(confidences)
    return 0.5  # Default when no service data available


def _get_confidence_from_validation(criterion, validation_map: dict) -> float:
    """Extract confidence score for a criterion from validation results."""
    if not criterion.services:
        return 1.0

    confidences = []
    for service in criterion.services:
        validation = validation_map.get(service)
        if validation:
            confidences.append(validation.confidence_score)

    if confidences:
        return min(confidences)
    return 0.5  # Default when no validation data available


def serialize_result(result: ForgeAssessmentResult) -> dict:
    """Convert a ForgeAssessmentResult dataclass into a JSON-serializable dict.

    Produces output matching the design's JSON schema with:
    - metadata: account_id, region, timestamp, collector_version, duration
    - pillars: per-pillar scores with per-criterion details
    - summary: forge_score, readiness_band, pillar_scores, coverage_multiplier, criteria_breakdown
    - scoring: dashboard format for forge_dashboard_generator.py compatibility

    The 'scoring' and 'pillars' top-level keys ensure the existing dashboard
    generator (which expects those keys) continues to work unchanged.

    Args:
        result: A ForgeAssessmentResult from run_assessment().

    Returns:
        A plain dict suitable for json.dump().
    """
    # Build per-pillar output
    pillars_output = []
    pillar_scores_dashboard = {}

    for pillar in result.pillars:
        criteria_output = []
        met_count = 0
        total_count = 0

        for cr in pillar.criteria:
            # Legacy dashboard compatibility: "met" = score >= 0.5 and relevant
            is_met = (
                cr.score >= 0.5
                and cr.relevance_status == RelevanceStatus.RELEVANT
            )
            if cr.relevance_status in (RelevanceStatus.RELEVANT, RelevanceStatus.UNDETERMINED):
                total_count += 1
                if is_met:
                    met_count += 1

            criteria_output.append({
                "index": cr.index,
                "name": cr.name,
                "score": cr.score,
                "met": is_met,
                "relevance_status": cr.relevance_status.value,
                "confidence_score": cr.confidence_score,
                "criterion_type": cr.criterion_type.value,
                "evidence": {
                    "description": cr.evidence,
                    "confidence_percent": round(cr.confidence_score * 100, 1),
                },
                "exclusion_reason": cr.exclusion_reason,
                "confidence_reduced": cr.confidence_reduced,
            })

        pillar_dict = {
            "code": pillar.code,
            "name": pillar.name,
            "total": total_count,
            "raw_score": pillar.raw_score,
            "relevant_count": pillar.relevant_count,
            "not_applicable_count": pillar.not_applicable_count,
            "undetermined_count": pillar.undetermined_count,
            "criteria": criteria_output,
        }
        pillars_output.append(pillar_dict)

        # Legacy format for dashboard generator
        pillar_scores_dashboard[pillar.code] = {
            "score_percent": pillar.raw_score,
            "met": met_count,
            "total": total_count,
        }

    # Build the full output dict
    output = {
        # Legacy top-level fields for forge_dashboard_generator.py compatibility
        "assessment_id": result.metadata.get("assessment_id", f"FORGE-{result.metadata.get('account_id', 'unknown')[:6]}"),
        "customer_name": result.metadata.get("customer_name", "Assessment Target"),
        "account_id": result.metadata.get("account_id", ""),
        "region": result.metadata.get("region", ""),
        "timestamp": result.metadata.get("timestamp", ""),
        "profile": result.metadata.get("profile", {}),
        # New modular format
        "metadata": result.metadata,
        "pillars": pillars_output,
        "summary": result.summary,
        # Legacy format for forge_dashboard_generator.py compatibility
        "scoring": {
            "forge_score": result.summary["forge_score"],
            "band": result.summary["readiness_band"],
            "raw_score": result.summary["raw_score"],
            "coverage_multiplier": result.summary["coverage_multiplier"],
            "pillar_scores": pillar_scores_dashboard,
            "penalty_percent": round((1.0 - result.summary["coverage_multiplier"]) * 100),
        },
    }

    return output


