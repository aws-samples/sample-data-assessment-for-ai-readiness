def run_assessment(
    account_id: str,
    region: str,
    profile_path: Path = Path("forge_output/forge_profile.yaml"),
    customer_name: str = "Assessment Target",
    relevance_config: RelevanceConfig = None,
    profile_name: str = None,
) -> ForgeAssessmentResult:
    """Execute a FORGE 2.3 assessment.

    Two modes of operation:

    Config mode (relevance_config provided):
        Load the pre-computed relevance map generated by the Kiro Skill.
        Skip probe, validate, and detect phases. Go straight to scoring.

    Legacy mode (no relevance_config):
        Execute full pipeline: probe → validate → classify → score.

    Args:
        account_id: 12-digit AWS account ID being assessed.
        region: AWS region to assess.
        profile_path: Path to the forge_profile.yaml file (contains the locked
            FORGE Profile declaration).
        customer_name: Display name for the assessment target.
        relevance_config: Pre-computed relevance config from Kiro Skill.
            If provided, skips probe/validate/detect phases.
        profile_name: AWS CLI profile name for boto3 session (full pipeline).

    Returns:
        ForgeAssessmentResult with metadata, per-pillar scores, and summary.
    """
    start_time = datetime.now(timezone.utc)

    # Load and resolve the FORGE Profile
    profile = load_profile(profile_path)
    resolved = resolve_profile(profile)
    effective_weights = resolved.effective_weights
    effective_floors = resolved.effective_floors

    # Display role permission scope summary (informational only, does not block)
    display_role_scope()

    if relevance_config is not None:
        # Config mode: use pre-computed relevance map
        criterion_results = _run_config_mode(relevance_config)
    else:
        # Full pipeline: execute probe → validate → classify → score
        criterion_results = _run_full_pipeline(
            region, None, profile_name
        )

    # Build per-pillar scores from criterion results
    pillars = _build_pillar_scores(criterion_results)

    # Compute pillar percentage map for formula
    pillar_pct_map = {p.code: p.raw_score for p in pillars}

    # Apply FORGE score formula using profile-derived weights and floors
    raw_score = compute_raw_score(pillar_pct_map, effective_weights)
    coverage_multiplier = compute_coverage_multiplier(pillar_pct_map, effective_floors)

    forge_score = compute_forge_score(raw_score, coverage_multiplier)
    readiness_band = classify_band(forge_score)

    end_time = datetime.now(timezone.utc)
    duration = (end_time - start_time).total_seconds()

    # Criteria breakdown
    relevant_count = sum(
        1 for cr in criterion_results if cr.relevance_status == RelevanceStatus.RELEVANT
    )
    not_applicable_count = sum(
        1 for cr in criterion_results if cr.relevance_status == RelevanceStatus.NOT_APPLICABLE
    )
    undetermined_count = sum(
        1 for cr in criterion_results if cr.relevance_status == RelevanceStatus.UNDETERMINED
    )

    # Profile info for metadata and summary
    profile_dict = {
        "architecture": profile.architecture.value,
        "workload": profile.workload.value,
        "industry": profile.industry.value,
        "agent_maturity": profile.agent_maturity.value,
    }

    # Build metadata
    metadata = {
        "account_id": account_id,
        "region": region,
        "customer_name": customer_name,
        "timestamp": start_time.isoformat(),
        "collector_version": VERSION,
        "assessment_duration_seconds": round(duration, 2),
        "relevance_config_used": relevance_config is not None,
        "profile": profile_dict,
    }

    # Build summary
    summary = {
        "forge_score": forge_score,
        "readiness_band": readiness_band.value,
        "raw_score": round(raw_score, 2),
        "coverage_multiplier": round(coverage_multiplier, 4),
        "effective_weights": effective_weights,
        "effective_floors": effective_floors,
        "pillar_scores": {p.code: p.raw_score for p in pillars},
        "criteria_breakdown": {
            "relevant": relevant_count,
            "not_applicable": not_applicable_count,
            "undetermined": undetermined_count,
        },
        "profile": profile_dict,
    }

    # Append history record (graceful failure)
    _append_history_record(
        start_time=start_time,
        forge_score=forge_score,
        readiness_band=readiness_band,
        pillar_pct_map=pillar_pct_map,
        profile=profile,
    )

    # Write assessment JSON artifact (graceful failure)
    _write_assessment_json(
        start_time=start_time,
        metadata=metadata,
        profile_dict=profile_dict,
        effective_weights=effective_weights,
        effective_floors=effective_floors,
        coverage_multiplier=coverage_multiplier,
        pillars=pillars,
        forge_score=forge_score,
        readiness_band=readiness_band,
        raw_score=raw_score,
        criterion_results=criterion_results,
    )

    # Write roadmap markdown artifact (graceful failure)
    _write_roadmap_md(
        start_time=start_time,
        pillars=pillars,
        pillar_pct_map=pillar_pct_map,
        effective_weights=effective_weights,
        forge_score=forge_score,
        readiness_band=readiness_band,
    )

    return ForgeAssessmentResult(
        metadata=metadata,
        pillars=pillars,
        summary=summary,
    )


def _append_history_record(
    start_time: datetime,
    forge_score: float,
    readiness_band,
    pillar_pct_map: dict[str, float],
    profile: ForgeProfile,
) -> None:
    """Append a single JSONL record to forge_history.jsonl.

    Creates the file if it does not exist. Opens in append mode only.
    Reports but does not abort on filesystem write failures.
    """
    history_record = {
        "timestamp": start_time.isoformat(),
        "forge_score": forge_score,
        "score_band": readiness_band.value,
        "pillar_scores": pillar_pct_map,
        "profile": {
            "architecture": profile.architecture.value,
            "workload": profile.workload.value,
            "industry": profile.industry.value,
            "agent_maturity": profile.agent_maturity.value,
        },
    }
    try:
        import os
        os.makedirs("forge_output", exist_ok=True)
        with open("forge_output/forge_history.jsonl", "a") as f:
            f.write(json.dumps(history_record) + "\n")
    except OSError as e:
        print(f"Warning: Could not write to forge_output/forge_history.jsonl: {e}")


def _write_assessment_json(
    start_time: datetime,
    metadata: dict,
    profile_dict: dict,
    effective_weights: dict[str, float],
    effective_floors: dict[str, int],
    coverage_multiplier: float,
    pillars: list[PillarScore],
    forge_score: float,
    readiness_band,
    raw_score: float,
    criterion_results: list[CriterionResult],
) -> None:
    """Write forge_assessment_<ts>.json with full assessment details.

    Reports but does not abort on filesystem write failures.
    """
    import os
    ts_filename = start_time.strftime("%Y-%m-%dT%H-%M-%SZ")
    os.makedirs("forge_output/assessments", exist_ok=True)
    filename = f"forge_output/assessments/forge_assessment_{ts_filename}.json"

    # Build pillar detail for the output
    pillars_output = []
    for pillar in pillars:
        criteria_output = []
        for cr in pillar.criteria:
            criteria_output.append({
                "index": cr.index,
                "name": cr.name,
                "score": cr.score,
                "relevance_status": cr.relevance_status.value,
                "confidence_score": cr.confidence_score,
                "criterion_type": cr.criterion_type.value,
                "evidence": cr.evidence,
                "exclusion_reason": cr.exclusion_reason,
            })
        pillars_output.append({
            "code": pillar.code,
            "name": pillar.name,
            "raw_score": pillar.raw_score,
            "relevant_count": pillar.relevant_count,
            "not_applicable_count": pillar.not_applicable_count,
            "undetermined_count": pillar.undetermined_count,
            "criteria": criteria_output,
        })

    output = {
        "metadata": metadata,
        "profile": profile_dict,
        "effective_weights": effective_weights,
        "effective_floors": effective_floors,
        "pillars": pillars_output,
        "scoring": {
            "forge_score": forge_score,
            "score_band": readiness_band.value,
            "raw_score": round(raw_score, 2),
            "coverage_multiplier": round(coverage_multiplier, 4),
        },
    }

    try:
        with open(filename, "w") as f:
            json.dump(output, f, indent=2)
    except OSError as e:
        print(f"Warning: Could not write {filename}: {e}")


def _load_recommendations() -> dict | None:
    """Load forge_config/recommendations.yaml if available.

    Returns parsed dict keyed by criterion ID (e.g. 'P1.7') or None.
    """
    candidates = [
        Path("forge_config/recommendations.yaml"),
        Path(__file__).resolve().parent.parent / "forge_config" / "recommendations.yaml",
    ]

    config_path = None
    for candidate in candidates:
        if candidate.exists():
            config_path = candidate
            break

    if config_path is None:
        return None

    try:
        import yaml
    except ImportError:
        return None

    try:
        with open(config_path, "r") as f:
            return yaml.safe_load(f)
    except (OSError, Exception):
        return None


