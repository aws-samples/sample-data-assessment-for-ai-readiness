def run_estate_assessment(
    segments: list[PlatformSegment],
    profile_path: Path = Path("forge_output/forge_profile.yaml"),
    customer_name: str = "Assessment Target",
) -> EstateAssessmentResult:
    """Run the estate-level assessment by merging platform segments.

    Takes pre-built platform segments (from AWS collector + Databricks skill),
    merges their criteria, and produces the estate score.

    Args:
        segments: List of PlatformSegment objects (at least one required).
        profile_path: Path to the forge_profile.yaml for weight/floor resolution.
        customer_name: Customer name for metadata.

    Returns:
        EstateAssessmentResult with all segments, merged criteria, and estate score.

    Raises:
        ValueError: If segments list is empty.
    """
    if not segments:
        raise ValueError("At least one platform segment is required")

    from forge.scoring_engine.merge import (
        merge_criteria,
        compute_estate_score,
        _build_pillar_scores_from_merged,
    )

    # Load profile
    profile = load_profile(profile_path)
    resolved = resolve_profile(profile)
    effective_weights = resolved.effective_weights
    effective_floors = resolved.effective_floors

    # Merge criteria across segments
    merged_criteria = merge_criteria(segments)

    # Compute estate score
    estate_score, estate_band, raw_score, coverage_multiplier = compute_estate_score(
        merged_criteria, effective_weights, effective_floors
    )

    # Build merged pillar scores (from merge engine)
    merged_pillars = _build_pillar_scores_from_merged(merged_criteria)

    # Build metadata
    metadata = {
        "customer_name": customer_name,
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "collector_version": VERSION,
        "platforms_assessed": [s.platform for s in segments],
    }

    result = EstateAssessmentResult(
        segments=segments,
        merged_pillars=merged_pillars,
        merged_criteria=merged_criteria,
        estate_score=estate_score,
        estate_band=estate_band,
        estate_raw_score=raw_score,
        estate_coverage_multiplier=coverage_multiplier,
        metadata=metadata,
    )

    # Write estate JSON
    _write_estate_json(result, effective_weights, effective_floors)

    # Append estate history record (graceful failure)
    _append_estate_history_record(result, profile)

    # Write estate roadmap markdown (multi-platform, platform-grouped)
    _write_estate_roadmap_md(result, effective_weights)

    return result


def _write_estate_json(
    result: EstateAssessmentResult,
    effective_weights: dict[str, float],
    effective_floors: dict[str, int],
) -> None:
    """Write estate assessment JSON artifact to forge_output/assessments/.

    Produces a file named forge_estate_assessment_<ts>.json with the format:
    {
      "metadata": {...},
      "profile": {...},
      "effective_weights": {...},
      "effective_floors": {...},
      "estate": {forge_score, score_band, raw_score, coverage_multiplier},
      "segments": [...],
      "merged_pillars": [...],
      "merged_criteria": [...]
    }

    Reports but does not abort on filesystem write failures.
    """
    import os

    ts_filename = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H-%M-%SZ")
    os.makedirs("forge_output/assessments", exist_ok=True)
    filename = f"forge_output/assessments/forge_estate_assessment_{ts_filename}.json"

    # Build segments output
    segments_output = []
    for segment in result.segments:
        criteria_output = []
        for cr in segment.criteria:
            cr_dict = {
                "pillar": cr.pillar,
                "index": cr.index,
                "name": cr.name,
                "score": cr.score,
                "relevance_status": cr.relevance_status.value,
                "confidence_score": cr.confidence_score,
                "evidence": cr.evidence,
                "criterion_type": cr.criterion_type.value,
                "platform": cr.platform,
                "exclusion_reason": cr.exclusion_reason,
            }
            if cr.analog_detail is not None:
                cr_dict["analog_detail"] = {
                    "numerator": cr.analog_detail.numerator,
                    "denominator": cr.analog_detail.denominator,
                    "platform": cr.analog_detail.platform,
                }
            criteria_output.append(cr_dict)

        pillars_output = []
        for pillar in segment.pillars:
            pillars_output.append({
                "code": pillar.code,
                "name": pillar.name,
                "raw_score": pillar.raw_score,
                "relevant_count": pillar.relevant_count,
                "not_applicable_count": pillar.not_applicable_count,
                "undetermined_count": pillar.undetermined_count,
            })

        segments_output.append({
            "platform": segment.platform,
            "source_type": segment.source_type,
            "forge_score": segment.summary.get("forge_score"),
            "score_band": segment.summary.get("readiness_band"),
            "pillars": pillars_output,
            "criteria": criteria_output,
        })

    # Build merged pillars output
    merged_pillars_output = []
    for pillar in result.merged_pillars:
        merged_pillars_output.append({
            "code": pillar.code,
            "name": pillar.name,
            "raw_score": pillar.raw_score,
            "relevant_count": pillar.relevant_count,
            "not_applicable_count": pillar.not_applicable_count,
            "undetermined_count": pillar.undetermined_count,
        })

    # Build merged criteria output
    merged_criteria_output = []
    for cr in result.merged_criteria:
        cr_dict = {
            "pillar": cr.pillar,
            "index": cr.index,
            "name": cr.name,
            "score": cr.score,
            "relevance_status": cr.relevance_status.value,
            "confidence_score": cr.confidence_score,
            "evidence": cr.evidence,
            "criterion_type": cr.criterion_type.value,
            "platform": cr.platform,
            "exclusion_reason": cr.exclusion_reason,
        }
        if cr.analog_detail is not None:
            cr_dict["analog_detail"] = {
                "numerator": cr.analog_detail.numerator,
                "denominator": cr.analog_detail.denominator,
                "platform": cr.analog_detail.platform,
            }
        merged_criteria_output.append(cr_dict)

    # Build full output
    output = {
        "metadata": result.metadata,
        "effective_weights": effective_weights,
        "effective_floors": effective_floors,
        "estate": {
            "forge_score": result.estate_score,
            "score_band": result.estate_band.value,
            "raw_score": round(result.estate_raw_score, 2),
            "coverage_multiplier": round(result.estate_coverage_multiplier, 4),
        },
        "segments": segments_output,
        "merged_pillars": merged_pillars_output,
        "merged_criteria": merged_criteria_output,
    }

    try:
        with open(filename, "w") as f:
            json.dump(output, f, indent=2)
    except OSError as e:
        print(f"Warning: Could not write {filename}: {e}")


def _append_estate_history_record(
    result: EstateAssessmentResult,
    profile: ForgeProfile,
) -> None:
    """Append an estate assessment record to forge_history.jsonl.

    Multi-platform format (len(segments) > 1):
    {
        "timestamp": "...",
        "estate_score": 59.8,
        "estate_band": "GOVERNED",
        "forge_score": 59.8,           # backward compat alias
        "score_band": "GOVERNED",      # backward compat alias
        "platform_scores": {"aws": 68.5, "databricks": 47.2},
        "pillar_scores": {"P1": 65.0, "P2": 55.0, ...},
        "platforms_assessed": ["aws", "databricks"],
        "profile": {...}
    }

    Backward compat (len(segments) == 1):
    Uses "forge_score" and "score_band" keys only (no estate_score/estate_band,
    no platform_scores, no platforms_assessed). Same format as existing
    _append_history_record output.

    Reports but does not abort on filesystem write failures.
    """
    # Build pillar scores from merged pillars
    pillar_scores = {p.code: p.raw_score for p in result.merged_pillars}

    # Profile dict
    profile_dict = {
        "architecture": profile.architecture.value,
        "workload": profile.workload.value,
        "industry": profile.industry.value,
        "agent_maturity": profile.agent_maturity.value,
    }

    timestamp = result.metadata.get("timestamp", datetime.now(timezone.utc).isoformat())

    if len(result.segments) == 1:
        # Single platform: backward-compatible format
        # Omit platform_scores and platforms_assessed
        history_record = {
            "timestamp": timestamp,
            "forge_score": result.estate_score,
            "score_band": result.estate_band.value,
            "pillar_scores": pillar_scores,
            "profile": profile_dict,
        }
    else:
        # Multi-platform: extended format
        platform_scores = {
            segment.platform: segment.summary.get("forge_score", 0.0)
            for segment in result.segments
        }
        history_record = {
            "timestamp": timestamp,
            "estate_score": result.estate_score,
            "estate_band": result.estate_band.value,
            "forge_score": result.estate_score,       # backward compat alias
            "score_band": result.estate_band.value,   # backward compat alias
            "platform_scores": platform_scores,
            "pillar_scores": pillar_scores,
            "platforms_assessed": [s.platform for s in result.segments],
            "profile": profile_dict,
        }

    try:
        import os
        os.makedirs("forge_output", exist_ok=True)
        with open("forge_output/forge_history.jsonl", "a") as f:
            f.write(json.dumps(history_record) + "\n")
    except OSError as e:
        print(f"Warning: Could not write to forge_output/forge_history.jsonl: {e}")


def _write_estate_roadmap_md(
    result: EstateAssessmentResult,
    effective_weights: dict[str, float],
) -> None:
    """Write multi-platform roadmap markdown to forge_output/roadmaps/.

    Produces a file named forge_estate_roadmap_<ts>.md with platform-grouped
    remediation sections. Each criterion is tagged with its platform.

    Format:
        # FORGE Estate Remediation Roadmap

        **Estate Score:** 59.8 (GOVERNED)
        **Platforms:** AWS (68.5), Databricks (47.2)

        ## AWS Remediation

        ### P1: Agent Access & Discovery
        - [ ] P1.6 — Catalog covers >80% (Evidence: ...)
        - [ ] P1.7 — Catalog descriptions (Evidence: ...)

        ## Databricks Remediation

        ### P4: Data Quality
        - [ ] P4.2 — Tables with DQ rules (Evidence: ...)
            - Services: Delta Live Tables

    Reports but does not abort on filesystem write failures.
    """
    import os

    ts_filename = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H-%M-%SZ")
    os.makedirs("forge_output/roadmaps", exist_ok=True)
    filename = f"forge_output/roadmaps/forge_estate_roadmap_{ts_filename}.md"

    # Import Databricks registry for service references
    try:
        from forge.platform_segments.databricks_registry import (
            DATABRICKS_SERVICES,
            get_databricks_criterion,
        )
        has_dbx_registry = True
    except ImportError:
        has_dbx_registry = False
        DATABRICKS_SERVICES = {}

    # Build header
    platform_scores_str = ", ".join(
        f"{seg.platform.upper()} ({seg.summary.get('forge_score', 0.0):.1f})"
        for seg in result.segments
    )

    lines = [
        "# FORGE Estate Remediation Roadmap",
        "",
        f"**Generated:** {result.metadata.get('timestamp', datetime.now(timezone.utc).isoformat())}",
        f"**Estate Score:** {result.estate_score:.1f} ({result.estate_band.value})",
        f"**Platforms:** {platform_scores_str}",
        "",
    ]

    # Group remediation by platform
    for segment in result.segments:
        # Find criteria with score < 0.5 and status RELEVANT for this platform
        unmet_criteria = [
            cr for cr in segment.criteria
            if cr.relevance_status == RelevanceStatus.RELEVANT and cr.score < 0.5
        ]

        if not unmet_criteria:
            lines.append(f"## {segment.platform.upper()} Remediation")
            lines.append("")
            lines.append("_No unmet criteria — all relevant criteria passing._")
            lines.append("")
            continue

        # Sort by pillar code, then by criterion index
        unmet_criteria.sort(key=lambda cr: (cr.pillar, cr.index))

        lines.append(f"## {segment.platform.upper()} Remediation")
        lines.append("")

        # Group by pillar
        current_pillar = None
        for cr in unmet_criteria:
            if cr.pillar != current_pillar:
                current_pillar = cr.pillar
                # Get pillar name from the segment's pillar scores
                pillar_name = current_pillar
                for p in segment.pillars:
                    if p.code == current_pillar:
                        pillar_name = p.name
                        break
                lines.append(f"### {current_pillar}: {pillar_name}")
                lines.append("")

            criterion_key = f"{cr.pillar}.{cr.index}"
            lines.append(f"- [ ] {criterion_key} — {cr.name}")

            # Add evidence if available
            if cr.evidence and cr.evidence != "No evidence":
                lines.append(f"  - Evidence: {cr.evidence}")

            # For Databricks criteria: include the service reference from registry
            if segment.platform == "databricks" and has_dbx_registry:
                dbx_criterion = get_databricks_criterion(cr.pillar, cr.index)
                if dbx_criterion and dbx_criterion.services:
                    service_names = [
                        DATABRICKS_SERVICES.get(svc, svc)
                        for svc in dbx_criterion.services
                    ]
                    lines.append(f"  - Services: {', '.join(service_names)}")

        lines.append("")

    content = "\n".join(lines)

    try:
        with open(filename, "w") as f:
            f.write(content)
    except OSError as e:
        print(f"Warning: Could not write {filename}: {e}")
